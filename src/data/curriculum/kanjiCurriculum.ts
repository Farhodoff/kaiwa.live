function makeItem(level: JlptLevel, kanji: string): KanjiLessonItem {
  const details = DETAILS[kanji];
  const [on, kun] = FALLBACK_READINGS[kanji] ?? ['オン', 'くん'];
  return {
    id: `lesson-kanji-${level.toLowerCase()}-${kanji.codePointAt(0)!.toString(16)}`,
    kanji,
    meanings: details?.meanings ?? [MEANINGS[kanji] ?? `${level} darajadagi kanji ma’nosi`],
    onyomi: details?.onyomi ?? [on],
    kunyomi: details?.kunyomi ?? (kun ? [kun] : ['—']),
    strokeCount: details?.strokeCount ?? Math.max(1, kanji.codePointAt(0)! % 17),
    exampleWords: details?.exampleWords ?? [
      { word: kanji, reading: kun || on, meaning: MEANINGS[kanji] ?? `${level} lug‘at so‘zi` },
    ],
    exampleSentence: details?.exampleSentence ?? `${kanji}という漢字を学びます。`,
    exampleTranslation: details?.exampleTranslation ?? `「${kanji}」 kanji belgisini o‘rganamiz.`,
    jlptLevel: level,
    strokeOrderAsset: `/data/kanjiStrokes.json#${encodeURIComponent(kanji)}`,
  };
}

export const KANJI_CURRICULUM: Record<JlptLevel, KanjiLessonItem[]> = Object.fromEntries(
  Object.entries(LEVEL_KANJI).map(([level, chars]) => [
    level,
    chars.map((char) => makeItem(level as JlptLevel, char)),
  ]),
) as Record<JlptLevel, KanjiLessonItem[]>;

/** Attach a deterministic, level-specific subset while leaving all existing course content intact. */
export function attachLessonKanji<T extends Lesson>(lessons: T[]): T[] {
  const cursor: Record<JlptLevel, number> = { N5: 0, N4: 0, N3: 0, N2: 0, N1: 0 };
  return lessons.map((lesson) => {
    if (!['N5', 'N4', 'N3', 'N2', 'N1'].includes(lesson.level)) return lesson;
    const level = lesson.level as JlptLevel;
    const source = KANJI_CURRICULUM[level];
    const start = cursor[level];
    const count = Math.min(2, source.length - start);
    cursor[level] += count;
    if (!count) return lesson;
    const learn = lesson.steps.find((step) => step.type === 'learn' && step.learnData);
    if (learn?.learnData) learn.learnData.kanji = source.slice(start, start + count);
    return lesson;
  });
}
