/**
 * Returns deterministic daily index from date string (YYYY-MM-DD or now)
 */
function getDayOfYearIndex(dateStr) {
  const d = dateStr ? new Date(dateStr) : new Date();
  const start = new Date(d.getFullYear(), 0, 0);
  const diff = (d - start) + ((start.getTimezoneOffset() - d.getTimezoneOffset()) * 60 * 1000);
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

export function getDailyKanji(dateStr) {
  const dayIdx = getDayOfYearIndex(dateStr);
  return DAILY_KANJI_LIST[Math.abs(dayIdx) % DAILY_KANJI_LIST.length];
}

export function getDailyVocab(dateStr) {
  const dayIdx = getDayOfYearIndex(dateStr);
  return DAILY_VOCAB_LIST[Math.abs(dayIdx) % DAILY_VOCAB_LIST.length];
}

