export function searchDailyContent(query = '') {
  const q = String(query).trim().toLowerCase();
  if (!q) {
    return {
      kanji: DAILY_KANJI_LIST.slice(0, 3),
      vocab: DAILY_VOCAB_LIST.slice(0, 3)
    };
  }

  const kanjiMatches = DAILY_KANJI_LIST.filter(k =>
    k.kanji.includes(q) ||
    k.meaning.toLowerCase().includes(q) ||
    k.onyomi.toLowerCase().includes(q) ||
    k.kunyomi.toLowerCase().includes(q) ||
    k.level.toLowerCase() === q
  );

  const vocabMatches = DAILY_VOCAB_LIST.filter(v =>
    v.word.includes(q) ||
    v.reading.toLowerCase().includes(q) ||
    v.meaning.toLowerCase().includes(q) ||
    v.level.toLowerCase() === q
  );

  return { kanji: kanjiMatches, vocab: vocabMatches };
}
